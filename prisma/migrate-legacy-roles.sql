-- Back up the database before running this script.
-- Run against an existing installation before applying the new Prisma schema.
-- Legacy mappings:
-- REQUESTER -> STAFF
-- WAREHOUSE_STAFF -> FARM_WH_PERSONNEL
-- ENGINEERING_WAREHOUSE_STAFF -> ENGINEERING_WH_PERSONNEL
-- APPROVER -> ENGINEERING_SUPERVISOR (as directed)

ALTER TABLE `User`
  MODIFY COLUMN `role` ENUM(
    'SUPER_ADMIN',
    'ADMIN',
    'ACCOUNTING',
    'FARM_WH_SUPERVISOR',
    'FARM_WH_PERSONNEL',
    'ENGINEERING_SUPERVISOR',
    'ENGINEERING_WH_PERSONNEL',
    'SALES_MANAGER',
    'EGG_ROOM_SUPERVISOR',
    'SALES_SUPERVISOR',
    'ADMIN_SUPERVISOR',
    'HR_SUPERVISOR',
    'MARKETING_SUPERVISOR',
    'PROCESS_ENGINEER',
    'EGG_ROOM_STAFF',
    'SALES_STAFF',
    'ADMIN_STAFF',
    'HR_ASSISTANT',
    'MARKETING_OFFICER',
    'MARKETING_STAFF',
    'PROCESS_ANALYST',
    'STAFF',
    'REQUESTER',
    'WAREHOUSE_STAFF',
    'ENGINEERING_WAREHOUSE_STAFF',
    'APPROVER'
  ) NOT NULL DEFAULT 'STAFF';

UPDATE `User`
SET `role` = CASE `role`
  WHEN 'REQUESTER' THEN 'STAFF'
  WHEN 'WAREHOUSE_STAFF' THEN 'FARM_WH_PERSONNEL'
  WHEN 'ENGINEERING_WAREHOUSE_STAFF' THEN 'ENGINEERING_WH_PERSONNEL'
  WHEN 'APPROVER' THEN 'ENGINEERING_SUPERVISOR'
  ELSE `role`
END
WHERE `role` IN ('REQUESTER', 'WAREHOUSE_STAFF', 'ENGINEERING_WAREHOUSE_STAFF', 'APPROVER');

